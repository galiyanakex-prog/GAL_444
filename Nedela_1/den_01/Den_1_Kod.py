# Импортируем модуль os для чтения переменных окружения.
import os
import sys

# Импортируем библиотеку для отправки HTTP-запросов к API.
import requests

# Импортируем функцию, которая загружает переменные из файла .env.
from dotenv import load_dotenv


# Загружаем переменные из файла .env в окружение программы.
load_dotenv()

# Получаем API-ключ из переменной окружения API_KEY.
api_key = os.getenv("API_KEY")

# Настраиваем кодировку stdin на UTF-8.
sys.stdin.reconfigure(encoding='utf-8')

# Проверяем, удалось ли найти API-ключ.
if not api_key:
    # Останавливаем программу и показываем понятную ошибку, если ключ отсутствует.
    raise RuntimeError(
        "Переменная API_KEY не найдена. "
        "Добавьте API-ключ в файл .env"
    )

# API endpoint RouterAI
url = "https://routerai.ru/api/v1/chat/completions"

# Заголовки запроса
headers = {
    "Authorization": f"Bearer {api_key}",
    "Content-Type": "application/json",
}

# Создаём список, в котором будет храниться история текущего диалога.
messages = [
    # Первым элементом добавляем системное сообщение с правилами для модели.
    {
        "role": "system",
        "content": "Ты полезный ассистент. Отвечай на русском языке.",
    }
]

# Выводим в консоль название программы.
print("🤖 Чат-бот на RouterAI")

# Объясняем пользователю, как завершить программу.
print("Введите «выход» для завершения.\n")

# Запускаем бесконечный цикл, чтобы пользователь мог отправлять много сообщений.
while True:
    # Показываем приглашение «Вы:», читаем ввод и удаляем пробелы по краям.
    user_input = input("Вы: ").strip()

    # Проверяем, ввёл ли пользователь команду завершения.
    if user_input.lower() == "выход":
        # Печатаем прощальное сообщение.
        print("До свидания!")

        # Прерываем бесконечный цикл и завершаем программу.
        break

    # Проверяем, осталась ли строка пустой после удаления пробелов.
    if not user_input:
        # Пропускаем текущую итерацию и снова ожидаем пользовательский ввод.
        continue

    # Добавляем новое сообщение пользователя в историю диалога.
    messages.append({"role": "user", "content": user_input})

    # Данные запроса: модель и вся история диалога.
    data = {
        "model": "stepfun/step-3.5-flash",
        "messages": messages,
    }

    # Начинаем блок обработки возможных ошибок при обращении к API.
    try:
        # Отправляем POST-запрос к API.
        response = requests.post(url, headers=headers, json=data, timeout=60)

        # Проверяем, что сервер вернул успешный статус, иначе показываем ошибку.
        response.raise_for_status()

        # Получаем JSON-ответ.
        result = response.json()

        # Получаем текст первого варианта ответа или пустую строку вместо None.
        bot_response = result["choices"][0]["message"]["content"] or ""

        # Добавляем успешный ответ модели в историю диалога.
        messages.append({"role": "assistant", "content": bot_response})

        # Выводим ответ модели и добавляем пустую строку для читаемости.
        print(f"Бот: {bot_response}\n")

    # Перехватываем ошибку HTTP (неверный ключ, недоступность сервиса и т.п.).
    except requests.exceptions.HTTPError as error:
        # Удаляем последнее сообщение пользователя, на которое модель не ответила.
        messages.pop()

        # Выводим понятное сообщение с текстом полученной ошибки.
        print(f"Ошибка HTTP при обращении к API: {error}\n")

    # Перехватываем сетевые ошибки (нет соединения, таймаут).
    except requests.exceptions.RequestException as error:
        # Удаляем последнее сообщение пользователя, на которое модель не ответила.
        messages.pop()

        # Выводим понятное сообщение с текстом полученной ошибки.
        print(f"Ошибка сети при обращении к API: {error}\n")

    # Перехватываем ошибки разбора ответа (неожиданный формат JSON).
    except (KeyError, IndexError, ValueError) as error:
        # Удаляем последнее сообщение пользователя, на которое модель не ответила.
        messages.pop()

        # Выводим понятное сообщение с текстом полученной ошибки.
        print(f"Неожиданный формат ответа API: {error}\n")

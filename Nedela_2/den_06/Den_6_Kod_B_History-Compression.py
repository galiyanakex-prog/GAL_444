# Активная история диалога: сообщения в окне и вне окна (ещё не сжатые).
full_history = []

# Архив сообщений, уже свёрнутых в саммари (для показа в /history).
archived = []

# Выводим шапку программы: название, размер окна, порог и имена файлов.
print(f"🤖 Чат-бот — День 6, History Compression (окно = {KEEP}, порог = {COMPRESS_THRESHOLD})")

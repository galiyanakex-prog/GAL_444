# КЛЮЧЕВАЯ ИДЕЯ:
# Вместо того чтобы выбрасывать старые сообщения (как в Sliding Window),
# мы сжимаем их в саммари отдельным вызовом LLM. Саммари всегда едет в
# запросе первым сообщением после system. Так контекст остаётся коротким,
# но агент «помнит» суть всего диалога. Цена — потеря деталей и лишние
# токены на сжатие.
#
# Compressed Memory: саммари сохраняется в файл и загружается при старте,
# поэтому сжатое знание переживает перезапуск программы (полная переписка — нет).

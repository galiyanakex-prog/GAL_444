# День 6, Вариант A — Sliding Window + Session Memory.
# Техника контекста: в запрос к LLM уходит только последние N сообщений (system не считается).
# Тип памяти: Session Memory — сессия стартует с чистого листа, лог пишется в файл,
# а загрузка прошлого лога в контекст делается вручную командой /load_history.

# Импортируем модуль os для чтения переменных окружения и работы с путями файлов.
import os
import sys

# Импортируем модуль traceback для записи полного стека ошибки в журнал.
import traceback

# Импортируем модуль time для паузы между повторами при HTTP 429.
import time

# Импортируем модуль argparse для разбора аргументов командной строки.
import argparse

# Импортируем модуль datetime для отметок времени в логе.
from datetime import datetime

# Импортируем библиотеку для отправки HTTP-запросов к API.
import requests

# Импортируем функцию, которая загружает переменные из файла .env.
from dotenv import load_dotenv


# Загружаем переменные из файла .env в окружение программы.
load_dotenv()

# Получаем API-ключ из переменной окружения API_KEY.
api_key = os.getenv("API_KEY")

# Настраиваем кодировку stdin на UTF-8, чтобы русский текст вводился корректно.
sys.stdin.reconfigure(encoding='utf-8')

# Проверяем, удалось ли найти API-ключ.
if not api_key:
    # Останавливаем программу и показываем понятную ошибку, если ключ отсутствует.
    raise RuntimeError(
        "Переменная API_KEY не найдена. "
        "Добавьте API-ключ в файл .env"
    )

# API endpoint RouterAI (OpenAI-совместимый).
URL = "https://routerai.ru/api/v1/chat/completions"

# Модель, через которую идут запросы.
MODEL = "stepfun/step-3.5-flash"

# Каталог этого скрипта: все файлы-артефакты привязываются к нему, а не к текущему
# каталогу — иначе .sh с `cd ../..` (рабочий каталог = корень AI_9) писал бы логи туда.
BASE_DIR = os.path.dirname(os.path.abspath(__file__))

# Имя лог-файла, в который сохраняется полная история диалога.
LOG_FILE = os.path.join(BASE_DIR, "Den_6_log_A_Sliding-Window.md")

# Заголовки HTTP-запроса: авторизация по ключу и тип данных JSON.
HEADERS = {
    "Authorization": f"Bearer {api_key}",
    "Content-Type": "application/json",
}

# System prompt — роль агента, отправляется первым сообщением в каждом запросе.
SYSTEM_PROMPT = "Ты полезный ассистент. Отвечай кратко на русском языке."

# Таймаут запроса к API в секундах.
REQUEST_TIMEOUT = 30

# Список задержек между повторами при HTTP 429 (экспоненциальная: 2 → 4 → 8 сек).
RETRY_DELAYS = [2, 4, 8]

# Имя файла журнала ошибок: сюда пишется полный стек любой непредвиденной ошибки.
ERROR_LOG = os.path.join(BASE_DIR, "den_6_error_A_Sliding-Window.log")


# Функция записи непредвиденной ошибки в журнал (с полным стеком вызовов).
def log_error(context, error):
    # Открываем журнал ошибок в режиме дозаписи с кодировкой UTF-8.
    with open(ERROR_LOG, "a", encoding="utf-8") as f:
        # Пишем разделитель с датой, временем и контекстом ошибки.
        f.write(f"\n{'=' * 60}\n")
        # Пишем время и место возникновения ошибки.
        f.write(f"[{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}] {context}\n")
        # Пишем тип ошибки и её сообщение.
        f.write(f"{type(error).__name__}: {error}\n")
        # Пишем полный стек вызовов — чтобы найти точное место падения.
        f.write(traceback.format_exc())
    # Дублируем краткое сообщение в консоль (окно может закрыться).
    print(f"[Ошибка] {context}: {error} (подробности в {ERROR_LOG})")


# Разбираем аргументы командной строки.
parser = argparse.ArgumentParser(
    description="Чат-бот с техникой Sliding Window (скользящее окно контекста)."
)

# Добавляем флаг --window: сколько последних сообщений держать в окне контекста.
parser.add_argument(
    "--window",
    type=int,
    default=10,
    help="Размер скользящего окна (количество последних сообщений).",
)

# Выполняем разбор аргументов и сохраняем результат.
args = parser.parse_args()

# Проверка размера окна: ноль или отрицательное число сделали бы окно пустым.
if args.window < 1:
    # Останавливаем программу с понятным объяснением.
    raise RuntimeError("Значение --window должно быть больше нуля.")

# Размер окна N — сколько последних сообщений (без system) уходит в запрос.
WINDOW = args.window


# Класс Agent — отдельная сущность, которая «знает» всё о диалоге:
# системную роль, размер окна, полную историю и то, как обращаться к LLM.
# Наружу (в CLI-цикл) отдаёт только ответы и сведения о контексте.
class Agent:
    # Создаём агента: системная роль + размер скользящего окна.
    def __init__(self, system_prompt: str, window: int = 10):
        # Системное сообщение (роль агента) — не входит в окно и не вытесняется.
        self.system_prompt = system_prompt

        # Размер скользящего окна: сколько последних сообщений уходит в запрос.
        self.window = window

        # Полная история диалога: все сообщения сессии, включая вытесненные из окна.
        self.full_history = []

        # Сколько сообщений из full_history уже записано в лог-файл.
        # Нужен, чтобы save_history() (и команда /save) дозаписывал только новые.
        self.saved_count = 0

        # Сколько сообщений уже было вытеснено из окна с начала сессии.
        self.evicted_total = 0

        # Флаг «окно сдвинулось на последнем шаге» — по нему CLI печатает уведомление.
        self.evicted_now = False

    # Внутренний метод: один запрос к LLM с повтором при HTTP 429.
    # Снаружи не вызывается — CLI работает только с send_message().
    def _ask_llm(self, messages):
        # Формируем тело запроса: модель и список сообщений.
        data = {
            "model": MODEL,
            "messages": messages,
        }

        # Перебираем попытки: первая обычная, дальше — с задержками из RETRY_DELAYS.
        for attempt in range(len(RETRY_DELAYS) + 1):
            # Начинаем блок обработки возможных ошибок при обращении к API.
            try:
                # Отправляем POST-запрос к API с таймаутом.
                response = requests.post(
                    URL, headers=HEADERS, json=data, timeout=REQUEST_TIMEOUT
                )

                # Если сервер вернул 429 (слишком много запросов) — пробуем ещё раз.
                if response.status_code == 429:
                    # Если это была последняя попытка — выходим из цикла с ошибкой.
                    if attempt == len(RETRY_DELAYS):
                        # Сообщаем пользователю, что лимит не снялся за все попытки.
                        print("[API] Лимит запросов: все повторы исчерпаны.\n")
                        # Возвращаем None — вызывающий код поймёт, что ответа нет.
                        return None

                    # Берём задержку для текущей попытки из списка.
                    delay = RETRY_DELAYS[attempt]

                    # Сообщаем пользователю, что ждём перед повтором.
                    print(f"[API] Лимит запросов, повтор через {delay} сек...")

                    # Приостанавливаем программу на указанное количество секунд.
                    time.sleep(delay)

                    # Переходим к следующей попытке.
                    continue

                # Проверяем остальные HTTP-ошибки (неверный ключ, недоступность и т.п.).
                response.raise_for_status()

                # Получаем JSON-ответ сервера.
                result = response.json()

                # Проверяем, что в ответе есть варианты ответа (choices).
                if "choices" not in result or not result["choices"]:
                    # Сообщаем о неожиданном формате ответа.
                    print("[API] Неожиданный формат ответа: нет choices.\n")
                    # Возвращаем None — ответа нет.
                    return None

                # Достаём текст первого варианта ответа модели.
                return result["choices"][0]["message"]["content"] or ""

            # Перехватываем ошибку HTTP (кроме уже обработанной 429).
            except requests.exceptions.HTTPError as error:
                # Выводим понятное сообщение с текстом ошибки.
                print(f"[API] Ошибка HTTP: {error}\n")
                # Возвращаем None — ответа нет.
                return None

            # Перехватываем сетевые ошибки (нет соединения, таймаут).
            except requests.exceptions.RequestException as error:
                # Выводим понятное сообщение с текстом ошибки.
                print(f"[API] Ошибка сети: {error}\n")
                # Возвращаем None — ответа нет.
                return None

            # Перехватываем ошибки разбора ответа (неожиданный формат JSON).
            except (KeyError, IndexError, ValueError) as error:
                # Выводим понятное сообщение об ошибке формата.
                print(f"[API] Неожиданный формат ответа API: {error}\n")
                # Возвращаем None — ответа нет.
                return None

    # Главный метод агента: принять сообщение пользователя и вернуть ответ LLM.
    def send_message(self, user_message: str):
        # Добавляем реплику пользователя в полную историю.
        self.full_history.append({"role": "user", "content": user_message})

        # Формируем запрос: [system] + последние N сообщений (само скользящее окно).
        messages = [{"role": "system", "content": self.system_prompt}] + self.full_history[-self.window:]

        # Отправляем запрос к LLM и получаем ответ (или None при ошибке).
        bot_response = self._ask_llm(messages)

        # Если ответа нет (ошибка API) — убираем реплику пользователя из истории,
        # чтобы она не «висела» без ответа и не попала в лог.
        if bot_response is None:
            # Удаляем последнее сообщение пользователя.
            self.full_history.pop()
            # Считаем, что окно на этом шаге не сдвигалось.
            self.evicted_now = False
            # Возвращаем None — CLI продолжит цикл без ответа.
            return None

        # Добавляем ответ модели в полную историю.
        self.full_history.append({"role": "assistant", "content": bot_response})

        # Считаем, сколько сообщений вытеснено из окна сейчас.
        evicted_now_total = max(0, len(self.full_history) - self.window)

        # Окно сдвинулось, если вытесненных стало больше, чем было до этого шага.
        self.evicted_now = evicted_now_total > self.evicted_total

        # Запоминаем новое количество вытесненных сообщений.
        self.evicted_total = evicted_now_total

        # Возвращаем текст ответа для вывода в консоль.
        return bot_response

    # Сохранение истории: дозаписывает в Markdown-лог только НОВЫЕ сообщения.
    # Счётчик saved_count гарантирует, что /save и /exit не создают дублей.
    def save_history(self, filepath: str):
        # Отбираем сообщения, которых ещё нет в файле.
        new_messages = self.full_history[self.saved_count:]

        # Если новых сообщений нет — файл не трогаем (пустых заголовков не плодим).
        if not new_messages:
            # Просто выходим: сохранять нечего.
            return

        # Открываем лог в режиме дозаписи с кодировкой UTF-8.
        with open(filepath, "a", encoding="utf-8") as f:
            # Пишем разделитель с текущими датой и временем — одна запись на сохранение.
            f.write(f"\n## {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")

            # Перебираем новые сообщения и пишем каждое отдельной строкой.
            for msg in new_messages:
                # Роль «user» показываем как «Вы», «assistant» — как «Агент».
                role = "Вы" if msg["role"] == "user" else "Агент"

                # Пишем строку формата «**Роль:** текст» — её же читает load_history().
                f.write(f"**{role}:** {msg['content']}\n")

        # Запоминаем, что теперь в файле лежит вся текущая история.
        self.saved_count = len(self.full_history)

    # Загрузка истории из Markdown-лога в память агента (команда /load_history).
    # Автоматически при старте НЕ вызывается: Session Memory начинается с чистого листа.
    def load_history(self, filepath: str):
        # Список, в который восстанавливаем сообщения из файла.
        loaded = []

        # Читаем файл построчно (кодировка UTF-8).
        with open(filepath, "r", encoding="utf-8") as f:
            # Перебираем все строки лога.
            for line in f:
                # Убираем пробелы и перевод строки по краям.
                line = line.strip()

                # Строка реплики пользователя: «**Вы:** текст».
                if line.startswith("**Вы:**"):
                    # Достаём текст после префикса и убираем лишние пробелы.
                    text = line[len("**Вы:**"):].strip()

                    # Пустые реплики в историю не добавляем.
                    if text:
                        # Добавляем сообщение с ролью «user».
                        loaded.append({"role": "user", "content": text})

                # Строка реплики агента: «**Агент:** текст».
                elif line.startswith("**Агент:**"):
                    # Достаём текст после префикса и убираем лишние пробелы.
                    text = line[len("**Агент:**"):].strip()

                    # Пустые реплики в историю не добавляем.
                    if text:
                        # Пропускаем повторяющиеся приветствия: каждый запуск
                        # дописывает в лог одинаковое «Привет! Я ваш помощник...»,
                        # и без этой проверки /load_history тащит их все в контекст.
                        if text == GREETING and any(
                            msg["content"] == GREETING for msg in loaded
                        ):
                            # Дубликат приветствия пропускаем.
                            continue

                        # Добавляем сообщение с ролью «assistant».
                        loaded.append({"role": "assistant", "content": text})

        # Восстановленная история становится полной историей агента.
        self.full_history = loaded

        # Все загруженные сообщения уже лежат в файле — помечаем их сохранёнными,
        # чтобы последующие /save и /exit не записали их повторно.
        self.saved_count = len(self.full_history)

        # Считаем заново, сколько сообщений стоит за пределами окна.
        self.evicted_total = max(0, len(self.full_history) - self.window)

        # На этом шаге окно не сдвигалось — уведомления не нужно.
        self.evicted_now = False

    # Очистка контекста: забываем историю сессии, лог-файл остаётся как есть.
    def clear_context(self):
        # Полностью очищаем историю диалога в памяти.
        self.full_history = []

        # Сбрасываем счётчик сохранённых сообщений: следующая запись — новая сессия.
        self.saved_count = 0

        # Сбрасываем счётчик вытесненных сообщений.
        self.evicted_total = 0

        # Уведомление о сдвиге окна не показываем.
        self.evicted_now = False

    # Краткое описание текущего контекста — для команды /window.
    def get_context_summary(self) -> str:
        # Считаем, сколько сообщений сейчас реально помещается в окне.
        in_window = min(len(self.full_history), self.window)

        # Возвращаем готовую строку для вывода.
        return f"[Окно] {in_window} из {self.window} сообщений"

    # Полная история с пометками для команды /history:
    # возвращаем список словарей {"role", "content", "in_window"}.
    def get_history(self) -> list:
        # Индекс первого сообщения, которое ещё попало в окно.
        in_window_from = max(0, len(self.full_history) - self.window)

        # Собираем результат: каждое сообщение + признак «в окне».
        return [
            {
                "role": msg["role"],
                "content": msg["content"],
                "in_window": index >= in_window_from,
            }
            for index, msg in enumerate(self.full_history)
        ]


# Функция вывода полной истории с пометками «в окне» / «вытеснено».
def show_history(history):
    # Если история пуста — сразу сообщаем об этом и выходим.
    if not history:
        # Печатаем пояснение и пустую строку для читаемости.
        print("[История] Пока пусто\n")
        # Завершаем работу функции.
        return

    # Перебираем сообщения, полученные от агента.
    for msg in history:
        # Определяем роль сообщения для отображения («Вы» или «Агент»).
        role = "Вы" if msg["role"] == "user" else "Агент"

        # Если сообщение ещё в окне — помечаем «в окне».
        if msg["in_window"]:
            # Печатаем сообщение с пометкой «в окне».
            print(f"[в окне] {role}: {msg['content']}")
        # Иначе сообщение уже вытеснено из окна.
        else:
            # Печатаем сообщение с пометкой «вытеснено».
            print(f"[вытеснено] {role}: {msg['content']}")

    # После списка печатаем пустую строку для читаемости.
    print()


# Заголовок лог-файла: создаём файл с шапкой, если его ещё нет.
if not os.path.exists(LOG_FILE):
    # Открываем файл на запись (создаём новый) с кодировкой UTF-8.
    with open(LOG_FILE, "w", encoding="utf-8") as f:
        # Пишем заголовок первого уровня с названием техники и размером окна.
        f.write(f"# Лог диалога — Sliding Window (N={WINDOW})\n")

# Если лог-файл уже существует — сообщаем, но в контекст его НЕ загружаем.
else:
    # Уведомление о найденном прошлом логе (Session Memory начинается с чистого листа).
    print(
        f"[Память] Найден прошлый лог: {LOG_FILE} "
        "(в контекст не загружается — сессия новая, /load_history — загрузить)"
    )

# Создаём агента: он один отвечает и за окно, и за историю, и за запросы к API.
agent = Agent(SYSTEM_PROMPT, window=WINDOW)

# Приветственное сообщение агента при старте.
GREETING = "Привет! Я ваш помощник. Чем могу помочь?"

# Выводим шапку программы: название, размер окна и имя лог-файла.
print(f"🤖 Чат-бот — День 6, Sliding Window (окно = {WINDOW})")
print(f"Лог: {LOG_FILE}")
print("Команды: /history, /window, /save, /load_history, /clear, /exit\n")

# Выводим приветствие агента в консоль.
print(f"Агент: {GREETING}\n")

# Дозаписываем приветствие в лог с отметкой времени.
with open(LOG_FILE, "a", encoding="utf-8") as f:
    # Пишем разделитель с текущими датой и временем.
    f.write(f"\n## {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
    # Пишем приветствие как реплику агента.
    f.write(f"**Агент:** {GREETING}\n")

# Запускаем бесконечный цикл, чтобы пользователь мог отправлять много сообщений.
# Весь цикл обёрнут в try/except: любая непредвиденная ошибка пишется в журнал,
# а программа не «молча» закрывает окно — она показывает ошибку и ждёт Enter.
while True:
    try:
        # Показываем приглашение «Вы:», читаем ввод и удаляем пробелы по краям.
        user_input = input("Вы: ").strip()

        # Обрабатываем команду /history — показать полную историю с пометками.
        if user_input == "/history":
            # Данные берём у агента, а не из «своего» списка — CLI не лезет в историю.
            show_history(agent.get_history())
            # Переходим к следующей итерации цикла.
            continue

        # Обрабатываем команду /window — показать текущее состояние окна.
        if user_input == "/window":
            # Строку описания контекста формирует сам агент.
            print(agent.get_context_summary())
            # Печатаем пустую строку для читаемости.
            print()
            # Переходим к следующей итерации цикла.
            continue

        # Обрабатываем команду /save — вручную сохранить историю в лог-файл.
        if user_input == "/save":
            # Сохранение делает агент: дозапишет только ещё не записанные сообщения.
            agent.save_history(LOG_FILE)
            # Сообщаем пользователю, что лог сохранён.
            print(f"[Память] Лог сохранён: {LOG_FILE}\n")
            # Переходим к следующей итерации цикла.
            continue

        # Обрабатываем команду /load_history — вручную загрузить лог в контекст.
        if user_input == "/load_history":
            # Проверяем, что файл лога вообще существует.
            if not os.path.exists(LOG_FILE):
                # Сообщаем об отсутствии файла и продолжаем работу (не падаем).
                print(f"[Память] Файл не найден: {LOG_FILE}\n")
                # Переходим к следующей итерации цикла.
                continue

            # Загрузку и разбор Markdown-лога выполняет агент.
            agent.load_history(LOG_FILE)

            # Считаем, сколько сообщений удалось восстановить.
            loaded_total = len(agent.get_history())

            # Считаем, сколько из них поместилось в окно контекста.
            in_window_total = min(loaded_total, WINDOW)

            # Показываем итог загрузки.
            print(
                f"[Память] Загружено сообщений: {loaded_total} "
                f"(в окне — {in_window_total} последних)\n"
            )
            # Переходим к следующей итерации цикла.
            continue

        # Обрабатываем команду /clear — очистить окно контекста.
        if user_input == "/clear":
            # Очистку делает агент: история в памяти стирается, файл остаётся.
            agent.clear_context()
            # Сообщаем пользователю об очистке.
            print("[Контекст] Окно очищено (лог-файл сохранён)\n")
            # Переходим к следующей итерации цикла.
            continue

        # Обрабатываем команду /exit — сохранить лог и выйти.
        if user_input == "/exit":
            # Перед выходом убедимся, что все сообщения записаны (дублей не будет).
            agent.save_history(LOG_FILE)
            # Сообщаем пользователю, что лог сохранён.
            print(f"[Память] Лог сохранён: {LOG_FILE}")
            # Прерываем бесконечный цикл и завершаем программу.
            break

        # Проверяем, осталась ли строка пустой после удаления пробелов.
        if not user_input:
            # Пропускаем текущую итерацию и снова ожидаем пользовательский ввод.
            continue

        # Отправляем сообщение агенту: окно, запрос к API и обновление истории — внутри.
        bot_response = agent.send_message(user_input)

        # Если ответа нет (ошибка API) — цикл продолжается, история не испорчена.
        if bot_response is None:
            # Переходим к следующей итерации цикла.
            continue

        # Выводим ответ модели и пустую строку для читаемости.
        print(f"Агент: {bot_response}\n")

        # Если агент сообщает, что окно сдвинулось, — предупреждаем пользователя.
        if agent.evicted_now:
            # Выводим ненавязчивое уведомление о вытеснении (один раз за сдвиг).
            print(
                f"[Контекст] Сообщение вышло из окна "
                f"(в памяти осталось {WINDOW} последних)\n"
            )

        # После каждого обмена дозаписываем новые сообщения в лог-файл.
        agent.save_history(LOG_FILE)

    # Перехватываем Ctrl+D (EOF) — корректный выход без ошибки.
    except EOFError:
        # Сообщаем о завершении и прерываем цикл.
        print("\n[Выход] Ввод завершён (EOF)")
        break

    # Перехватываем Ctrl+C — корректный выход без traceback.
    except KeyboardInterrupt:
        # Сообщаем о прерывании и прерываем цикл.
        print("\n[Выход] Прервано пользователем")
        break

    # Перехватываем любую другую непредвиденную ошибку в теле цикла.
    except Exception as error:
        # Записываем полный стек ошибки в журнал ошибок.
        log_error("Ошибка в главном цикле", error)
        # Просим нажать Enter, чтобы окно не закрылось мгновенно.
        input("Нажмите Enter для продолжения...")
